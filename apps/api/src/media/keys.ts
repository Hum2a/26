const gameKey = /^[ABCDEFGHJKLMNPQRSTUVWXYZ23456789]{8,32}$/;
const objectId = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

export function temporaryKey(gameId: string, uploadId: string): string {
  assertKeyPart(gameId.toUpperCase(), gameKey);
  assertKeyPart(uploadId, objectId);
  return `tmp/${gameId.toUpperCase()}/${uploadId}`;
}

export function acceptedKey(gameId: string, mediaId: string): string {
  assertKeyPart(gameId.toUpperCase(), gameKey);
  assertKeyPart(mediaId, objectId);
  return `accepted/${gameId.toUpperCase()}/${mediaId}`;
}

function assertKeyPart(value: string, pattern: RegExp): void {
  if (!pattern.test(value)) {
    throw new Error("That media key was not generated by this room.");
  }
}
